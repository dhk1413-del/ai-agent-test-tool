function bank() {
  const categories = CATEGORIES.map(c => {
    const groups = c.groups.map(g => ({ name: g.name, questions: g.questions.slice() }));
    const total = groups.reduce((n, g) => n + g.questions.length, 0);
    return { id: c.id, name: c.name, icon: c.icon, desc: c.desc, groups, total };
  });
  return {
    categories,
    total: categories.reduce((n, c) => n + c.total, 0),
    defaults: DEFAULT_QUESTIONS.slice(),
  };
}

